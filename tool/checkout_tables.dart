// Turns the checkout tables in data/checkout-tables (izlazi-1-strelica.csv,
// izlazi-2-strelice.csv, izlazi-3-strelice.csv) into
// lib/src/domain/checkout_tables.dart.
//
//   dart run tool/checkout_tables.dart
import 'dart:io';

/// One CSV line split into its fields; a field in quotes may hold commas.
List<String> _fields(String line) {
  final fields = <String>[];
  final field = StringBuffer();
  var quoted = false;
  for (final char in line.split('')) {
    if (char == '"') {
      quoted = !quoted;
    } else if (char == ',' && !quoted) {
      fields.add(field.toString());
      field.clear();
    } else {
      field.write(char);
    }
  }
  fields.add(field.toString());
  return fields;
}

String _literal(String text) => "'${text.trim().replaceAll('–', '').replaceAll("'", r"\'")}'";

void main() {
  final out = StringBuffer()
    ..writeln('// Generated by tool/checkout_tables.dart from data/checkout-tables. Do not edit.')
    ..writeln()
    ..writeln("import 'checkout_table.dart';")
    ..writeln()
    ..writeln('/// Darts in hand -> number -> its row of the checkout tables.')
    ..writeln('const Map<int, Map<int, CheckoutTableRow>> checkoutTables = {');
  for (final (darts, file) in [(1, 'izlazi-1-strelica.csv'), (2, 'izlazi-2-strelice.csv'), (3, 'izlazi-3-strelice.csv')]) {
    final lines = File('data/checkout-tables/$file').readAsLinesSync();
    final header = _fields(lines.first);
    int column(String name) => header.indexOf(name);
    out.writeln('  $darts: {');
    for (final line in lines.skip(1)) {
      if (line.trim().isEmpty) continue;
      final f = _fields(line);
      String at(String name) => column(name) < 0 ? '' : f[column(name)];
      out.writeln('    ${f[0]}: CheckoutTableRow(${_literal(at('Gađaj'))}, ${_literal(at('Ruta'))}, '
          '${_literal(at('Pravilo'))}, ${_literal(at('Alternativa'))}),');
    }
    out.writeln('  },');
  }
  out.writeln('};');
  File('lib/src/domain/checkout_tables.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote lib/src/domain/checkout_tables.dart');
}
